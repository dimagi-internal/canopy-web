"""Slack as a front door to canopy agents.

Framework tier: a transport, agent-agnostic, like ``inbound``. A Slack thread
becomes a ``canopy_sessions.Session`` exactly as an email thread does; see
``docs/superpowers/specs/2026-09-18-slack-front-door-design.md``.

Two rows, and deliberately nothing that grants anything:

* ``SlackInstallation`` — one Slack team, bound to one canopy Workspace. The bot
  token lives here, encrypted. The agent never sees it.
* ``SlackUserLink`` — "this Slack user is this canopy user", made by that person
  signing in, and only when the two email addresses agree (see ``views_auth``).
  Being in the Slack workspace is not being in the canopy workspace: a link
  without a membership is refused at send time.
"""
from __future__ import annotations

import uuid

from django.conf import settings
from django.db import models

from apps.common.encryption import decrypt_secret, encrypt_secret


class SlackInstallation(models.Model):
    team_id = models.CharField(max_length=32, unique=True)
    team_name = models.CharField(max_length=255, blank=True, default="")
    bot_user_id = models.CharField(max_length=32)
    bot_token_enc = models.TextField()
    # No tenant here: one Slack can serve several canopy workspaces, each
    # through a `SlackWorkspaceLink`. The tenant of any message is decided by
    # what it is about (its thread's session, or the agent it names) — see
    # docs/superpowers/specs/2026-09-22-slack-multi-tenant-design.md.
    installed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True,
        related_name="+",
    )
    installed_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    #: The Slack app's id, captured from the OAuth exchange. Needed to edit the
    #: app's own manifest (its slash commands) — see apps/slack/commands.py.
    app_id = models.CharField(max_length=32, blank=True, default="")

    # --- managing the app's slash commands ------------------------------------
    # An APP CONFIGURATION token, generated by a Slack user who collaborates on
    # the app. It can rewrite the app itself, so it is held like the bot token:
    # encrypted, owner-set, never returned. The access token lives 12h; the
    # refresh token is SINGLE-USE and rotates, so exactly one writer may use it
    # at a time (commands.py locks the row) and the new one must be stored
    # every time or the pair is lost.
    config_token_enc = models.TextField(blank=True, default="")
    config_refresh_enc = models.TextField(blank=True, default="")
    config_expires_at = models.DateTimeField(null=True, blank=True)
    config_set_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name="+",
    )
    commands_synced_at = models.DateTimeField(null=True, blank=True)
    commands_sync_error = models.CharField(max_length=300, blank=True, default="")
    #: When this app was declared an agent (`commands.declare_agent`), which is
    #: what lets Slack draw its own working indicator. A local note about a fact
    #: that lives in Slack's manifest: it answers "has anyone done this yet?"
    #: without an API round trip on every settings page load.
    agent_declared_at = models.DateTimeField(null=True, blank=True)
    #: The bot scopes this install actually granted, comma-separated, as Slack
    #: reported them (the OAuth exchange, or `X-OAuth-Scopes` for an install
    #: from before this was kept). A scope added to the app later lands only on
    #: a re-install, and this is how the settings page knows one is due.
    granted_scopes = models.TextField(blank=True, default="")

    def __str__(self) -> str:  # pragma: no cover
        return self.team_name or self.team_id

    def workspace_ids(self) -> list[str]:
        """The canopy workspaces this Slack serves, earliest link first."""
        return list(self.links.order_by("linked_at", "pk").values_list("workspace_id", flat=True))

    @property
    def home_workspace_id(self) -> str | None:
        """The earliest-linked tenant: where a message that resolved to no
        tenant is logged. Never used to decide access."""
        ids = self.workspace_ids()
        return ids[0] if ids else None

    @property
    def manages_commands(self) -> bool:
        return bool(self.app_id and self.config_refresh_enc)

    @property
    def bot_token(self) -> str:
        return decrypt_secret(self.bot_token_enc)

    @bot_token.setter
    def bot_token(self, plaintext: str) -> None:
        self.bot_token_enc = encrypt_secret(plaintext)


class SlackWorkspaceLink(models.Model):
    """One canopy workspace served by one Slack. Many per Slack, one per tenant.

    Created by an owner of the workspace completing Slack's install (the OAuth
    callback), with no sign-off from tenants already linked: a link adds a
    tenant beside them and grants it nothing of theirs.
    """

    installation = models.ForeignKey(SlackInstallation, on_delete=models.CASCADE, related_name="links")
    # NOT NULL, like every other tenant FK here: a nullable one is how six
    # predicates grew a "no tenant => allow" leg (see agents/0013).
    workspace = models.OneToOneField(
        "workspaces.Workspace", on_delete=models.CASCADE, related_name="slack_link",
    )
    linked_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name="+",
    )
    linked_at = models.DateTimeField(auto_now_add=True)
    # `--history <minutes>` (apps/slack/window.py): whether an ask in Slack may
    # hand an agent this channel's recent past, and how far back. Per tenant,
    # because the agent that receives it is this tenant's; set by an owner on
    # the Slack settings page.
    history_enabled = models.BooleanField(default=True)
    history_max_minutes = models.PositiveIntegerField(default=120)
    # A whole-channel read for an agent (apps/slack/ingest.py): whether this
    # tenant's agents may ASK for one at all. Off until an owner opts in; every
    # ingest still needs its own in-channel approval on top of this.
    channel_ingest_enabled = models.BooleanField(default=False)

    def __str__(self) -> str:  # pragma: no cover
        return f"{self.installation} -> {self.workspace_id}"


class SlackChannelIngestAllow(models.Model):
    """An admin's (or owner's) standing, explicit permission for ONE agent to read ONE channel whole.

    The in-channel Approve click (`ingest.decide`) is one way a person grants a
    whole-channel read; this is the other: a workspace owner or admin names the channel
    and the agent ahead of time, on the Slack settings page or the API. A
    request that matches an entry starts reading at once — it is approved by
    whoever added the entry, and canopy still posts a notice (with
    Revoke) in the channel so its members can see it. An entry is its own
    opt-in: it works whether or not `channel_ingest_enabled` is on, and
    removing it revokes the reads it allowed. See apps/slack/ingest.py.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    workspace = models.ForeignKey("workspaces.Workspace", on_delete=models.CASCADE,
                                  related_name="slack_channel_allows")
    installation = models.ForeignKey(SlackInstallation, on_delete=models.CASCADE,
                                     related_name="channel_allows")
    agent = models.ForeignKey("agents.Agent", on_delete=models.CASCADE, related_name="slack_channel_allows")
    channel_id = models.CharField(max_length=32)
    channel_name = models.CharField(max_length=255, blank=True, default="")
    #: May the agent also keep following the channel, or only read it once?
    follow = models.BooleanField(default=False)
    note = models.CharField(max_length=500, blank=True, default="")
    added_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True,
                                 blank=True, related_name="+")
    added_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["agent", "channel_id"], name="slack_allow_agent_channel")]

    def __str__(self) -> str:  # pragma: no cover
        return f"{self.agent_id} may read {self.channel_id}"


class SlackChannelIngest(models.Model):
    """An agent's permission to read one Slack channel whole — and the read.

    Created PENDING by a request; nothing is read until a person eligible to
    approve presses Approve on the message canopy posts in that channel
    (`ingest.decide`). canopy then reads the channel itself, off-request
    (`ingest.advance`), into `SlackIngestMessage` rows; the agent only ever
    gets the rendered transcript, never a token. See apps/slack/ingest.py.
    """

    PENDING, READING, READY, DECLINED, REVOKED, FAILED = (
        "pending", "reading", "ready", "declined", "revoked", "failed")
    STATUS_CHOICES = [(s, s) for s in (PENDING, READING, READY, DECLINED, REVOKED, FAILED)]
    #: Where the read is: paging the channel, paging the threads it found, or idle.
    HISTORY, THREADS, IDLE = "history", "threads", "idle"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    workspace = models.ForeignKey("workspaces.Workspace", on_delete=models.CASCADE,
                                  related_name="slack_channel_ingests")
    installation = models.ForeignKey(SlackInstallation, on_delete=models.CASCADE,
                                     related_name="channel_ingests")
    agent = models.ForeignKey("agents.Agent", on_delete=models.CASCADE, related_name="slack_channel_ingests")
    channel_id = models.CharField(max_length=32)
    channel_name = models.CharField(max_length=255, blank=True, default="")
    purpose = models.TextField()
    #: Keep reading new messages into the same transcript until revoked.
    follow = models.BooleanField(default=False)
    requested_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True,
                                     blank=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default=PENDING)
    #: The approval post in the channel — the only place a decision can come from.
    approval_ts = models.CharField(max_length=32, blank=True, default="")
    decided_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True,
                                   blank=True, related_name="+")
    decided_by_slack_id = models.CharField(max_length=32, blank=True, default="")
    decided_at = models.DateTimeField(null=True, blank=True)
    revoked_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True,
                                   blank=True, related_name="+")
    revoked_by_slack_id = models.CharField(max_length=32, blank=True, default="")
    revoked_at = models.DateTimeField(null=True, blank=True)

    # --- the read: resumable state ---------------------------------------
    phase = models.CharField(max_length=10, default=HISTORY)
    history_cursor = models.CharField(max_length=500, blank=True, default="")
    #: `oldest` for the history pass in progress ("" = the whole channel).
    history_oldest = models.CharField(max_length=32, blank=True, default="")
    #: Threads still to read: [[parent_ts, oldest], …]; the head is in progress.
    thread_queue = models.JSONField(default=list, blank=True)
    thread_cursor = models.CharField(max_length=500, blank=True, default="")
    #: A follow pass keeps only what is newer than this.
    follow_since = models.CharField(max_length=32, blank=True, default="")
    latest_ts = models.CharField(max_length=32, blank=True, default="")
    #: Slack user id -> display name, fetched once per person.
    names = models.JSONField(default=dict, blank=True)
    messages = models.PositiveIntegerField(default=0)
    batches = models.PositiveIntegerField(default=0)
    #: Not before this: set from Slack's Retry-After, or a back-off after an error.
    next_attempt_at = models.DateTimeField(null=True, blank=True)
    backfilled_at = models.DateTimeField(null=True, blank=True)
    followed_at = models.DateTimeField(null=True, blank=True)
    error = models.CharField(max_length=300, blank=True, default="")
    #: How far the agent has read: the last `SlackIngestMessage` id it kept (0 = nothing yet).
    #: A transcript read `after` it holds only what canopy stored since, so a recurring
    #: turn catches up instead of re-reading the channel (`ingest.transcript`, `mark_read`).
    read_mark = models.PositiveBigIntegerField(default=0)
    read_at = models.DateTimeField(null=True, blank=True)
    #: Set when the read was granted by an owner's allow-list entry, not a click.
    allowance = models.ForeignKey(SlackChannelIngestAllow, on_delete=models.SET_NULL, null=True, blank=True,
                                  related_name="ingests")
    #: A person's `/<agent> read-channel <ask>` waiting on this read: the Slack
    #: message it came from and the ask. When the pass finishes, canopy hands the
    #: agent everything since `read_mark` with the ask, in that message's thread,
    #: and clears this (`ingest.read_channel`, `_deliver`). Empty = nobody waiting.
    pending_ask = models.JSONField(default=dict, blank=True)

    class Meta:
        indexes = [models.Index(fields=["status", "next_attempt_at"], name="slack_ingest_due")]

    def __str__(self) -> str:  # pragma: no cover
        return f"{self.agent_id} <- {self.channel_id} ({self.status})"


class SlackIngestMessage(models.Model):
    """One message of an ingested channel. Unique per (ingest, ts), so a page
    re-read after a rate limit or a follow pass inserts nothing twice."""

    ingest = models.ForeignKey(SlackChannelIngest, on_delete=models.CASCADE, related_name="lines")
    ts = models.CharField(max_length=32)
    #: The parent's ts for a reply; "" for a channel message.
    thread_ts = models.CharField(max_length=32, blank=True, default="")
    user = models.CharField(max_length=32, blank=True, default="")
    name = models.CharField(max_length=255, blank=True, default="")
    text = models.TextField(blank=True, default="")

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["ingest", "ts"], name="slack_ingest_message_once"),
        ]


