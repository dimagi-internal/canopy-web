"""Lazy imports (ruff PLC0415, import-outside-toplevel) — a new one must say why, and
the old ones can only go.

pyproject turns PLC0415 on for production source under `apps/` and `config/` (tests
and migrations are exempt), and CI's ruff step runs it. An import inside a function
hides a dependency, and usually a cycle, from everyone reading the top of the file;
it is allowed only with a reason on the line:

    from .credentials import zk  # cycle: agents.credentials.zk -> agents.services  # noqa: PLC0415
    from weasyprint import HTML  # noqa: PLC0415 — 40 MB, only the PDF export needs it

Every file that had unjustified lazy imports when the rule went on is listed in
`ruff-lazy-imports.toml`, a per-file ignore for ruff, with its count in a trailing
comment. This test holds those counts as a RATCHET: more lazy imports in a listed
file fails (hoist the import, or justify it with a `noqa`), and fewer fails too,
with the line to change or delete, so the list only shrinks. After a rebase, or
once you have hoisted imports, `uv run python -m tests.test_lazy_import_baseline
--write` rewrites the file from the tree.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter

from tests._source import ROOT, is_migration, is_test_file

BASELINE = ROOT / "ruff-lazy-imports.toml"
SCOPE = ("apps", "config")
_ENTRY = re.compile(r'^"(?P<path>[^"]+)" = \["PLC0415"\]  # (?P<count>\d+)$')
_NOQA = re.compile(r"#\s*noqa:[^#]*\bPLC0415\b")


def frozen() -> dict[str, int]:
    """The baseline's per-file counts, from its `"path" = ["PLC0415"]  # n` lines."""
    found = {}
    for line in BASELINE.read_text().splitlines():
        if m := _ENTRY.match(line):
            found[m["path"]] = int(m["count"])
        elif line.startswith('"'):
            raise AssertionError(f"malformed baseline line in {BASELINE.name}: {line}")
    return found


def current() -> Counter[str]:
    """Unjustified lazy imports per production file, read by ruff itself — `--isolated`
    so the baseline's own ignores don't hide them; a `noqa` still does."""
    out = subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--isolated", "--select", "PLC0415",
         "--exclude", "**/migrations/*", "--output-format", "json", "--exit-zero", *SCOPE],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    counts: Counter[str] = Counter()
    for finding in json.loads(out):
        rel = finding["filename"][len(str(ROOT)) + 1:]
        if not (is_test_file(rel) or is_migration(rel)):
            counts[rel] += 1
    return counts


def test_no_new_lazy_imports() -> None:
    base, now = frozen(), current()
    grown = {f: n for f, n in now.items() if n > base.get(f, 0)}
    assert not grown, (
        "New import(s) inside a function (ruff PLC0415). Hoist each to the top of the "
        "module, or, if it must stay lazy (a cycle, a heavy optional dependency), say why "
        "on the line: `# noqa: PLC0415 — <reason>`. Don't raise the count in "
        f"{BASELINE.name}:\n"
        + "\n".join(f"  {f}: {n}, {base.get(f, 0)} allowed" for f, n in sorted(grown.items()))
    )


def test_baseline_only_shrinks() -> None:
    base, now = frozen(), current()
    shrunk = {f: now.get(f, 0) for f, n in base.items() if now.get(f, 0) < n}
    assert not shrunk, (
        f"Lazy imports were hoisted — thank you. Ratchet {BASELINE.name} down to match "
        "(or run `uv run python -m tests.test_lazy_import_baseline --write`):\n"
        + "\n".join(f'  delete  "{f}"' if n == 0 else f'  change  "{f}"  # {base[f]}  →  # {n}'
                    for f, n in sorted(shrunk.items()))
    )


def test_every_justified_lazy_import_says_why() -> None:
    """A `noqa: PLC0415` is the reason a lazy import is allowed, so it must carry one."""
    bare = []
    for d in SCOPE:
        for path in sorted((ROOT / d).rglob("*.py")):
            rel = path.relative_to(ROOT).as_posix()
            if is_test_file(rel) or is_migration(rel):
                continue
            for n, line in enumerate(path.read_text().splitlines(), 1):
                if (m := _NOQA.search(line)) is None:
                    continue
                comment = line[line.index("#"):]
                reason = comment.replace(m.group(0), "").strip(" #—-:")
                if not reason:
                    bare.append(f"{rel}:{n}")
    assert not bare, ("`# noqa: PLC0415` with no reason — add one (`# noqa: PLC0415 — <why>`, "
                      "or `# cycle: a -> b  # noqa: PLC0415`):\n  " + "\n  ".join(bare))


_HEADER = """\
# Lazy-import baseline — GENERATED by `uv run python -m tests.test_lazy_import_baseline --write`.
#
# Every file below had imports inside functions (ruff PLC0415) when the rule went on;
# ruff ignores PLC0415 in them, and the trailing number is how many they have.
# tests/test_lazy_import_baseline.py holds those numbers as a ratchet: they may only
# go down, and a file leaves the list when it reaches zero. A new lazy import goes at
# the top of the module, or carries `# noqa: PLC0415 — <reason>`.
# pyproject.toml extends this file.

[lint.per-file-ignores]
"""


if __name__ == "__main__":  # `python -m tests.test_lazy_import_baseline [--write]`
    table = "".join(f'"{f}" = ["PLC0415"]  # {n}\n' for f, n in sorted(current().items()))
    if "--write" in sys.argv:
        BASELINE.write_text(_HEADER + table)
    else:
        print(table, end="")
